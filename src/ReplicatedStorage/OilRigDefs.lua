-- Темп (README, раздел 7)
-- ⚠️ REST_TIME НЕ БОЛЬШЕ, ЧЕМ DRILL_TIME − TRIP_TIME.
-- Это гарантированный отдых ПОСЛЕ ходки; если он длиннее интервала бурения,
-- узким местом становится носильщик и дневная норма недобирается. Сейчас 10 при
-- интервале ~22 — запас есть. Сверх этих 10 он всё равно стоит на точке, пока у
-- бурильщика не поспеет следующая порция, так что отдых выходит длиннее.
OilRig.REST_TIME    = 10    -- минимальный отдых носильщика на своей точке
OilRig.MAX_QUEUE    = 3     -- больше не копит, уходит в простой
OilRig.POUR_AT      = 28/30 -- момент опрокидывания внутри клипа Pour
OilRig.COINS_PER_CAN = 4    -- монет игроку за ходку

-- ⚠️ НЕФТЬ ИДЁТ В БАК НА ПЛОТУ, В ТЕХ ЖЕ МИЛЛИЛИТРАХ, ЧТО И ВСЁ ТОПЛИВО.
-- Одна ходка даёт мало нарочно: вышка — фоновый доход, а не замена канистрам.
OilRig.ML_MIN = 10
OilRig.ML_MAX = 15

-- Сумма пауз в самой ходке (OilRigSystem: дошёл 1.6, поднял 1, донёс 2.5,
-- опрокинул POUR_AT, долил 1.4, вернулся 2). Ниже этого срока цикл не ужать.
OilRig.TRIP_TIME = 8.5 + OilRig.POUR_AT

-- ── СМЕНА ──
-- ⚠️ ЧАСЫ БЕРЁМ ИЗ ОБЩЕГО ЦИКЛА, А НЕ СВОИ.
-- Весь проект считает время по Lighting.ClockTime: день 6→18, ночь 18→6
-- (DayNightCircle.server.lua). Длительности оттуда же — день 380 реальных
-- секунд, ночь 120. Поменяешь их в DayNightCircle — поправь и здесь, иначе
-- дневная норма разъедется с вывеской.
OilRig.DAY_START     = 6     -- рассвет по общему циклу
OilRig.DAY_END       = 18    -- закат по общему циклу
OilRig.DAY_SECONDS   = 380   -- реальных секунд в светлой половине
OilRig.NIGHT_SECONDS = 120   -- реальных секунд в тёмной

-- Смена: встали в 6:30, ушли домой спать в 23:00.
OilRig.WORK_START = 6.5
OilRig.WORK_END   = 23

-- ⚠️ СМЕНА ЗАХОДИТ В ТЁМНОЕ ВРЕМЯ, И ЧАСЫ ТАМ КОРОЧЕ.
-- День 380 секунд на 12 игровых часов, ночь 120 на те же 12 — то есть ночной час
-- втрое быстрее дневного. Считать смену «в часах» нельзя: с 18:00 до 23:00 это
-- пять часов, но всего 50 реальных секунд. Поэтому переводим каждый кусок по
-- своей ставке.
local function realSeconds(fromHour, toHour)
	local dayRate   = OilRig.DAY_SECONDS   / (OilRig.DAY_END - OilRig.DAY_START)
	local nightRate = OilRig.NIGHT_SECONDS / (24 - (OilRig.DAY_END - OilRig.DAY_START))
	local total = 0
	for h = 0, 23 do          -- по часу: кусок ложится либо в день, либо в ночь
		local a = math.max(fromHour, h)
		local b = math.min(toHour, h + 1)
		if b > a then
			local light = (h >= OilRig.DAY_START and h < OilRig.DAY_END)
			total += (b - a) * (light and dayRate or nightRate)
		end
	end
	return total
end

OilRig.WORK_SECONDS = realSeconds(OilRig.WORK_START, OilRig.WORK_END)

-- ⚠️ ГЛАВНАЯ РУЧКА — ДНЕВНАЯ НОРМА, А НЕ ИНТЕРВАЛ.
-- На вывеске у скважины написано «Добыча — N мл/день», и цифра там обязана
-- совпадать с тем, что реально капает в бочку. Поэтому крутим ИМЕННО норму, а
-- интервал бурения считается из неё: иначе вывеска и игра расходятся, и первым
-- это замечает игрок. Уровень пока один, дальше сюда же ляжет таблица улучшений.
OilRig.LEVEL        = 1
OilRig.RATE_PER_DAY = 200   -- мл за игровой день на 1 уровне

local function avgMl()
	return (OilRig.ML_MIN + OilRig.ML_MAX) / 2
end

-- Сколько ждать между порциями, чтобы за смену вышло ровно RATE_PER_DAY.
-- Быстрее, чем носильщик успевает обернуться, всё равно не получится — отсюда
-- нижняя граница.
OilRig.DRILL_TIME = math.max(
	OilRig.TRIP_TIME + OilRig.REST_TIME,
	OilRig.WORK_SECONDS / (OilRig.RATE_PER_DAY / avgMl()))

-- Настоящая добыча — считаем обратно от интервала, а не берём RATE_PER_DAY на
-- веру: если он окажется недостижимым и сработает ограничение выше, на вывеске
-- должно быть честное число.
function OilRig.mlPerDay()
	return math.floor(OilRig.WORK_SECONDS / OilRig.DRILL_TIME * avgMl() + 0.5)
end

