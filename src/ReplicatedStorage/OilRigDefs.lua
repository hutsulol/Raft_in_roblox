-- ⚠️ ДЕКОР НЕ СЧИТАЕТСЯ ЗАНЯТЫМ МЕСТОМ.
-- Проверка «в габарите ничего постороннего» ловила ЛЮБУЮ деталь, и поставить
-- что-нибудь на остров стало почти нельзя: трава, ракушки, грибы и мелкие камни
-- (Rocks_024 и такие же) рассыпаны сплошняком. Реально мешают только крупные
-- объекты — пальмы, валуны обода, чужие постройки. Отсюда три признака декора:
--   • деталь без коллизии (вся зелень в паках такая);
--   • имя из списка ниже;
--   • просто МЕЛКАЯ — камешек в пару студов постройке не помеха.
-- Правило общее для сервера и призрака: две копии разъехались бы, и призрак
-- горел бы зелёным там, где сервер отказывает.
OilRig.DECOR_PREFIX = {
	"Plants_", "Plant_", "Grass", "Bush", "Fern", "Shell", "Coral",
	"Flower", "Mushroom", "Rocks_", "Rock_", "Seaweed", "Weed", "Kelp",
}
OilRig.DECOR_MAX = 6   -- студов по наибольшей стороне

-- А это, наоборот, мешает всегда: свои же постройки друг на друге не ставим,
-- какими бы мелкими ни были их отдельные детали.
OilRig.SOLID_MODELS = { OilRig_station = true, House_home = true, Farm_Island_Build = true, Farm_Build_Island_Sheep = true }

function OilRig.isDecor(part)
	if not part:IsA("BasePart") then return true end
	-- деталь чужой постройки — не декор, даже если она размером с доску
	local m = part
	while m and m ~= workspace do
		if OilRig.SOLID_MODELS[m.Name] then return false end
		m = m.Parent
	end
	if not part.CanCollide then return true end
	local n = part.Name
	for _, p in ipairs(OilRig.DECOR_PREFIX) do
		if n:sub(1, #p) == p then return true end
	end
	local s = part.Size
	return math.max(s.X, s.Y, s.Z) <= OilRig.DECOR_MAX
end

