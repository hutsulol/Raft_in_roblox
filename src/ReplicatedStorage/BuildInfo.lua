-- BuildInfo.lua  (ReplicatedStorage, общий модуль)
-- ГДЕ МЫ ЗАПУЩЕНЫ И КУДА ОТСЮДА ВЕДЁТ ДОРОГА. Одна короткая метка для угла
-- меню («v1_po») и одна карта мест на всю игру: по ней же считается, в какой
-- океан увозит лобби и в какое лобби возвращает океан.
--
-- ⚠️ НОМЕР ПУБЛИКАЦИИ БОЛЬШЕ НЕ ПОКАЗЫВАЕМ.
-- Здесь стоял game.PlaceVersion — он растёт сам при каждой выкладке и честно
-- отвечал на вопрос «какой билд крутится». Но владелец ведёт свою нумерацию
-- обновлений, и «v10» на экране вместо «v1» путало сильнее, чем помогало.
-- Строка VERSION ниже — единственный номер, который видит игрок.
--------------------------------------------------------------------

local RunService = game:GetService("RunService")

local BuildInfo = {}

--[[ ⚠️ НОМЕР ВЕРСИИ ВЕДЁМ СВОЙ, А НЕ БЕРЁМ У ROBLOX.
     Здесь печатался game.PlaceVersion — номер ПУБЛИКАЦИИ. Он растёт сам при
     каждой выкладке, и на экране появлялось «v10» там, где по договорённости
     должна стоять «v1»: к содержанию обновления номер публикации отношения не
     имеет. Строка одна на все места и все плейсы — правится здесь. ]]
BuildInfo.VERSION = "v3"

--[[ ⚠️ КАРТА МЕСТ — ЕДИНСТВЕННЫЙ ИСТОЧНИК ПРАВДЫ ПРО ПЛЕЙСЫ.
     Roblox не знает слов «прод» и «стейдж»: место для него просто число.
     Три среды, в каждой пара «лобби ↔ океан»; pair — парное место СВОЕЙ среды:
     из лобби туда уезжают начинать игру, из океана туда же возвращают после
     проигрыша.
     Раньше дев-среды здесь не было вовсе, а дев-океан 77272676169005 числился
     стейджем. Телепорт при этом работал верно, но подпись в углу сообщала
     «СТЕЙДЖ · океан» — и выглядело это как «зашёл в дев-лобби, попал в стейдж».
     Ошибалась именно надпись; чтобы такого не повторилось, теперь и надпись, и
     сам телепорт читают одну эту таблицу.
     Числа плейсов раньше жили ещё и вписанными руками: OCEAN_PLACE_ID в пяти
     файлах каждого лобби (а лобби три) и LOBBY_PLACE_ID в океане — полтора
     десятка мест, обязанных совпадать. Достаточно ошибиться в одном. ]]
BuildInfo.PLACES = {
	[106626615985973] = { env = "ДЕВ",    what = "лобби", pair = 77272676169005  },
	[77272676169005]  = { env = "ДЕВ",    what = "океан", pair = 106626615985973 },

	[119629266018246] = { env = "СТЕЙДЖ", what = "лобби", pair = 102373706486912 },
	[102373706486912] = { env = "СТЕЙДЖ", what = "океан", pair = 119629266018246 },

	[81459221324058]  = { env = "ПРОД",   what = "лобби", pair = 139922101356393 },
	[139922101356393] = { env = "ПРОД",   what = "океан", pair = 81459221324058  },
}

--[[ Парное место своей среды. kind — «океан» или «лобби».
     ⚠️ ЗАПАСНОЕ ЗНАЧЕНИЕ ОБЯЗАТЕЛЬНО, И ВОТ ПОЧЕМУ.
     В Studio PlaceId бывает нулевым (локальный файл) или чужим (открыли копию
     чужого места). Вернуть в таком случае nil значило бы сломать телепорт там,
     где раньше всё работало по вписанному числу. Поэтому вызывающая сторона
     передаёт своё прежнее число, и оно используется, пока карта молчит. ]]
local function partnerOf(kind, fallback)
	local here = BuildInfo.PLACES[game.PlaceId]
	if here and here.pair then
		local other = BuildInfo.PLACES[here.pair]
		if other and other.what == kind then return here.pair end
	end
	return fallback
end

-- Из лобби: океан своей среды. Из океана: лобби своей среды.
function BuildInfo.oceanPlace(fallback) return partnerOf("океан", fallback) end
function BuildInfo.lobbyPlace(fallback) return partnerOf("лобби", fallback) end

function BuildInfo.place()
	return BuildInfo.PLACES[game.PlaceId]
end

--[[ ⚠️ СРЕДУ ПИШЕМ КОДОМ, А НЕ СЛОВОМ.
     В углу настроек стояло «ПРОД · океан · v1» — открытым текстом, кто где
     находится. Игроку эта надпись не говорит ничего полезного, зато сообщает
     посторонним, что плейсов несколько и какой из них боевой.
     Теперь одна короткая метка: v1_po. Первая буква — среда (д/с/п), вторая —
     половина пары (океан/лобби), обе латиницей по русским словам:
        v1_do — дев океан      v1_dl — дев лобби
        v1_so — стейдж океан   v1_sl — стейдж лобби
        v1_po — прод океан     v1_pl — прод лобби
     Свой человек читает её с одного взгляда, чужой не читает вовсе. Номер
     версии остаётся впереди — он и есть главное в этой строке. ]]
local ENV_CODE  = { ["ДЕВ"] = "d", ["СТЕЙДЖ"] = "s", ["ПРОД"] = "p" }
local KIND_CODE = { ["океан"] = "o", ["лобби"] = "l" }

--[[ Короткий код сборки: «v1_po».
     ⚠️ НЕИЗВЕСТНОЕ МЕСТО — «v1_??», А НЕ МОЛЧАНИЕ И НЕ «ПРОД».
     Забыть новый плейс в карте легко: он заводится раньше, чем правится код.
     Выдать такое место за прод — худшее из решений: подмены никто не заметит,
     и ошибку найдут уже по жалобам. Два вопроса в метке ни с чем не спутать. ]]
function BuildInfo.tag()
	local place = BuildInfo.place()
	if not place then return BuildInfo.VERSION .. "_??" end
	return ("%s_%s%s"):format(BuildInfo.VERSION,
		ENV_CODE[place.env] or "?", KIND_CODE[place.what] or "?")
end

-- Короткая строка для угла экрана.
function BuildInfo.label()
	local tag = BuildInfo.tag()

	--[[ ⚠️ В STUDIO ДОПИСЫВАЕМ ПОДРОБНОСТИ, В ИГРЕ — НЕТ.
	     Редактор видит только разработчик, и здесь важнее другое: три плейса в
	     Studio выглядят одинаково, а ошибка «правил не ту среду» вскрывается
	     уже после публикации. Поэтому в редакторе к коду добавляется слово
	     Studio, а для места вне карты — ещё и сам номер плейса, иначе вписать
	     его в PLACES не по чему. ]]
	if RunService:IsStudio() then
		if BuildInfo.place() then return tag .. " · Studio" end
		return tag .. " · Studio · плейс " .. tostring(game.PlaceId)
	end

	return tag
end

return BuildInfo
