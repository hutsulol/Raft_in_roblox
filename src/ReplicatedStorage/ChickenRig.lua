--[[
	ChickenRig — wires the six imported MeshParts into a Motor6D skeleton.

	Put this next to ChickenRigData (generated by chicken.py) as ModuleScripts:

		ReplicatedStorage/Chicken/
			ChickenRig          <- this file
			ChickenRigData      <- generated offsets
			ChickenAnimator
			Model               <- the Model from Chicken.fbx

	Usage:
		local Rig = require(ReplicatedStorage.Chicken.ChickenRig)
		local chicken = Rig.spawn(CFrame.new(0, 3, 0))
		chicken.animator:play("IdlePeck")

	Joint tree:
		HumanoidRootPart --RootJoint--> chicken_torso
			chicken_torso --Neck--> chicken_head
			chicken_torso --WingL/WingR--> chicken_wing_l / _r
			chicken_torso --HipL/HipR--> chicken_leg_l / _r
]]

local Data = require(script.Parent.ChickenRigData)
local Animator = require(script.Parent.ChickenAnimator)

local Rig = {}

local PART_NAMES = {
	"chicken_torso", "chicken_head",
	"chicken_wing_l", "chicken_wing_r",
	"chicken_leg_l", "chicken_leg_r",
}

-- how far the lowest toe sits below the model origin, so spawn CFrames can be
-- given at ground level instead of guessing
Rig.GroundOffset = Data.GroundOffset

--[[ Turns a freshly imported Model into a rigged one. Safe to call on a clone. ]]
function Rig.setup(model: Model)
	local parts = {}
	for _, name in ipairs(PART_NAMES) do
		local p = model:FindFirstChild(name, true)
		assert(p and p:IsA("BasePart"), "ChickenRig: missing part " .. name)
		p.Anchored = false
		p.CanCollide = false
		p.CanQuery = false
		p.CanTouch = false
		p.Massless = true
		-- a mesh imported at 100 units per stud comes in oversized unless the
		-- importer was told otherwise; leave Size alone but keep the scale honest
		parts[name] = p
	end

	local torso = parts.chicken_torso
	torso.Massless = false

	local root = model:FindFirstChild("HumanoidRootPart")
	if not root then
		root = Instance.new("Part")
		root.Name = "HumanoidRootPart"
		root.Size = Vector3.new(0.9, 1.0, 1.2)
		root.Transparency = 1
		root.CanCollide = true
		root.CanQuery = false
		root.CFrame = torso.CFrame
		root.Parent = model
	end

	-- clear anything left over so setup is idempotent
	for _, d in ipairs(model:GetDescendants()) do
		if d:IsA("Motor6D") or d:IsA("WeldConstraint") or d:IsA("Weld") then
			d:Destroy()
		end
	end

	local motors = {}

	local rj = Instance.new("Motor6D")
	rj.Name = "RootJoint"
	rj.Part0 = root
	rj.Part1 = torso
	-- на случай, если HumanoidRootPart уже был в модели и повёрнут иначе
	rj.C0 = root.CFrame:Inverse() * torso.CFrame
	rj.C1 = CFrame.new()
	rj.Parent = root
	motors.Root = rj

	for _, j in ipairs(Data.Joints) do
		local m = Instance.new("Motor6D")
		m.Name = j.name
		m.Part0 = parts[j.part0]
		m.Part1 = parts[j.part1]
		-- ⚠️ БЕРЕЖЁМ АВТОРСКИЙ ПОВОРОТ ДЕТАЛИ (правка против оригинала пакета).
		-- У импортированной головы её поворот запечён в CFrame детали (180° к
		-- торсу), а ЧИСТЫЕ переносы C0/C1 из данных приравнивали поворот детали
		-- к торсовому — голова вставала задом наперёд. Поэтому: точка сустава —
		-- из данных, в осях торса (C0 — перенос, клипы читаются как раньше), а
		-- C1 снимаем с ФАКТИЧЕСКОЙ авторской позы — деталь остаётся, как стояла.
		local p0, p1 = parts[j.part0], parts[j.part1]
		local jointWorld = p0.CFrame * CFrame.new(j.c0)
		m.C0 = CFrame.new(j.c0)
		m.C1 = p1.CFrame:Inverse() * jointWorld
		m.Parent = p0
		motors[j.name] = m
	end

	model.PrimaryPart = root

	return {
		model = model,
		root = root,
		parts = parts,
		motors = motors,
		animator = Animator.new(motors),
	}
end

--[[ Clones the template model, rigs it, drops it in Workspace. ]]
function Rig.spawn(cframe: CFrame, parent: Instance?)
	local template = script.Parent:FindFirstChild("Model")
	assert(template, "ChickenRig: no Model next to the module")
	local model = template:Clone()
	local chicken = Rig.setup(model)
	model.Parent = parent or workspace
	model:PivotTo(cframe * CFrame.new(0, -Rig.GroundOffset, 0))
	return chicken
end

return Rig
