--[[
	КАК ЕДА САДИТСЯ НА РЕШЁТКУ — общий расчёт для сервера и призрака.

	⚠️ РАНЬШЕ ЭТО СЧИТАЛОСЬ ТОЛЬКО НА СЕРВЕРЕ.
	Призрак показывал кусок в авторском размере, сервер клал ужатый — и на
	предпросмотре было одно, а по факту другое. Теперь обе стороны зовут одну
	функцию, и разойтись им нечем.

	⚠️ УЖИМАЕМ ПО ТОЙ СТОРОНЕ, ЧТО ЛОЖИТСЯ ВДОЛЬ РЕШЁТКИ, А НЕ ПО САМОЙ БОЛЬШОЙ.
	Первый заход брал максимум из ВСЕХ трёх измерений. У продолговатого куска,
	который кладут набок, самой большой оказывалась длина — и он сжимался так,
	будто должен уместиться в слот целиком поперёк. Отсюда «ставится слишком
	маленькая еда». Поперёк слота стоит только одна сторона, её и меряем.
]]

local GrillFit = {}

-- Ниже этого не ужимаем: лучше пусть соседние куски чуть соприкоснутся, чем
-- на решётке будут лежать крошки, в которых не узнать, что жарится.
GrillFit.MIN_SCALE = 0.55

-- Кусок кладут набок, если он заметно выше, чем шире.
function GrillFit.laysDown(size)
	return size.Y > math.max(size.X, size.Z) * 1.1
end

-- Сколько занимает поперёк слота после укладки.
function GrillFit.acrossSlot(size)
	if GrillFit.laysDown(size) then
		-- лёг набок: поперёк встаёт МЕНЬШАЯ из горизонтальных сторон
		return math.min(size.X, size.Z)
	end
	return math.min(size.X, size.Z)
end

-- Во сколько раз ужать, чтобы влезло в слот. Никогда не увеличиваем: мелкую
-- еду раздувать до размера слота — не то же самое, что уместить крупную.
function GrillFit.scaleFor(size, slotWidth)
	local across = GrillFit.acrossSlot(size)
	if across <= 0 or slotWidth <= 0 then return 1 end
	if across <= slotWidth then return 1 end
	return math.clamp(slotWidth / across, GrillFit.MIN_SCALE, 1)
end

-- Ширина одного места на решётке. Держится в одном месте, потому что её считают
-- и сервер (куда класть), и клиент (куда целится призрак).
function GrillFit.slotWidth(grateSize, slots)
	return math.max(grateSize.X, grateSize.Z) * 0.88 / math.max(slots, 1)
end

return GrillFit
