-- Это ЕДИНСТВЕННОЕ место, где описана культура. Чтобы добавить третью (морковь),
-- нужно ровно два действия:
--   1) папка ReplicatedStorage/Crops/Carrot с тремя мешами Sprout/Young/Ripe;
--   2) одна строка в этой таблице.
-- Ни один скрипт и ни один объект в мире при этом трогать не надо — именно так
-- проверяется, что получилась система, а не набор частных случаев.
--
-- Поля:
--   displayName  — подпись в интерфейсе;
--   growSeconds  — сколько ПОЛИТОГО времени до спелости (сухая грядка не растёт);
--   stages       — имена мешей в ReplicatedStorage/Crops/<культура>/;
--   yield        — сколько штук даёт сбор.
--                  ⚠️ ЧЕТЫРЕ, ПОТОМУ ЧТО НА ГРЯДКЕ ВИДНО ЧЕТЫРЕ. Спелая
--                  грядка рисует четыре овоща, а отдавала три — игрок
--                  считал глазами и не сходилось. Число тут обязано
--                  совпадать с мешем стадии Ripe; меняешь меш — меняй и его;
--   seed         — ключ ресурса, который тратится при посадке. Совпадает с
--                  урожаем: сажаем картофелину — получаем картофелины.

return {
	Potato = {
		displayName = "Картофель",
		growSeconds = 180,
		stages      = { "Sprout", "Young", "Ripe" },
		yield       = 4,
		seed        = "Potato",
	},
	Beet = {
		displayName = "Свёкла",
		-- В брифе у свёклы было 220 секунд и урожай 2, но правило игры одно для
		-- всех: посадил одну — собрал четыре. Время оставил чуть длиннее картофеля,
		-- чтобы культуры отличались хоть чем-то.
		growSeconds = 220,
		stages      = { "Sprout", "Young", "Ripe" },
		yield       = 4,
		seed        = "Beet",
	},
}
