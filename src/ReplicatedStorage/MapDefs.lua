--[[ ⚠️ ЦЕНА РЕЙСА — В ЛИТРАХ, А БАК НА ПЛОТУ ХРАНИТ МИЛЛИЛИТРЫ (OilStored).
     Раньше сервер вычитал «4 нефти» как 4 мл из 100 000 — на экране бака в
     литрах это ноль, и казалось, что рейс бесплатный. Сервер умножает цену на
     этот коэффициент перед проверкой и списанием. ]]
Map.OIL_UNIT_ML = 1000
function Map.sailCost(dxStuds, dzStuds)
	local d = math.sqrt(dxStuds * dxStuds + (dzStuds * 0.65) ^ 2)
	return math.max(4, math.round(d * Map.OIL_PER_STUD))
end

-- Квадратичная Безье маршрута: контрольная точка = середина плюс перпендикуляр.
function Map.routeControl(a, b)
	local mid = (a + b) * 0.5
	local d = b - a
	local len = d.Magnitude
	if len < 0.001 then return mid end
	local k = math.min(8, len * 0.18)
	local perp = Vector2.new(-d.Y, d.X) / len
	return mid + perp * k
end

function Map.bezier(a, c, b, t)
	local u = 1 - t
	return a * (u * u) + c * (2 * u * t) + b * (t * t)
end

