     молча меняла стоимость всех рейсов. Коэффициент подобран так, что цены
     остались ровно теми же, что были при масштабе 0.055 (0.055 × 0.6).
     Множитель 0.65 по оси Z — из прототипа: карта шире, чем выше, и ход
