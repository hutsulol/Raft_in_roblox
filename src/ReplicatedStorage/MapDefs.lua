--[[ ⚠️ РАСХОД НЕФТИ СЧИТАЕТСЯ ОДНОЙ ФОРМУЛОЙ НА ДВОИХ.
     Клиент показывает цену на кнопке, сервер по ней же списывает. Разойдутся —
     игрок увидит одну цифру, а спишется другая; сервер тут источник истины.
