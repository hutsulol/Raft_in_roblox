--[[
	OctopusRig — wires the 21 imported MeshParts into a Motor6D skeleton, runs
	the hundred-click kill, and lets the same parts fly apart as loot.

		ReplicatedStorage/Octopus/
			OctopusRig        <- this file
			OctopusRigData    <- generated by octo_split.py
			OctopusAnimator
			Model             <- the Model from Octopus.fbx (21 MeshParts)

		local Rig = require(ReplicatedStorage.Octopus.OctopusRig)
		local octo = Rig.spawn(CFrame.new(0, 6, -40))
		octo:onClick(function(left) print(left .. " to go") end)

	Rigid parts only. Nothing here is skinned and nothing is scaled at runtime:
	every clip is whole parts rotating and translating on their joints. That is
	the one thing that behaves identically in Studio, in a live server and on
	every client.

	The skeleton is one deep — head is the root, everything hangs off it, and
	each tentacle is base -> tip so it can bend. The tips are modelled with a
	sleeve over the base, so the joint does not open a slit when it swings.
]]

local RunService = game:GetService("RunService")
local DebrisSvc = game:GetService("Debris")

local Data = require(script.Parent.OctopusRigData)
local Animator = require(script.Parent.OctopusAnimator)

local Rig = {}
Rig.__index = Rig

Rig.MaxHits = 100
Rig.HitCooldown = 0.04     -- a floor on click spam, so 100 taps cannot land in one frame
Rig.Lifetime = 25          -- seconds it stays up before giving up and sinking
Rig.GoldNames = { crown = true, collar = true, trinket = true }

--[[ Смещения в RigData записаны в стадах — для импорта со Scale 0.01. Привезли
     модель крупнее или мельче, и они уедут ровно во столько же раз. Считаем
     масштаб по самим деталям: их габариты в таблице тоже есть. ]]
local function importScale(parts)
	local sum, n = 0, 0
	for name, p in pairs(parts) do
		local want = Data.Parts[name] and Data.Parts[name].size
		if want and want.Magnitude > 1e-3 then
			sum += p.Size.Magnitude / want.Magnitude
			n += 1
		end
	end
	return (n > 0) and (sum / n) or 1
end

--[[ Turns a freshly imported Model into a rigged one. Safe to call on a clone.

     ⚠️ ОБЯЗАТЕЛЬНА ТОЛЬКО ГОЛОВА, ОСТАЛЬНОЕ — ПО НАЛИЧИЮ.
     Раньше здесь стоял assert на каждую из двадцати деталей, и модель без одной
     ДЕКОРАТИВНОЙ подвески не собиралась вовсе: в логе «missing part trinket» и
     ни одного осьминога в море. 3D Importer вполне может не привезти мелочь
     (у trinket толщина 0.09 стада), и терять из-за неё всю тушу — несоразмерно.
     Чего нет, того просто нет: сустав не создаётся, аниматор такую дорожку не
     находит и молча её пропускает. ]]
function Rig.setup(model: Model)
	local parts, missing = {}, {}
	for name in pairs(Data.Parts) do
		local p = model:FindFirstChild(name, true)
		if p and p:IsA("BasePart") then
			p.Anchored = false
			p.CanCollide = false
			p.CanQuery = true          -- the player has to be able to click it
			p.Massless = true
			parts[name] = p
		else
			table.insert(missing, name)
		end
	end
	local head = parts[Data.Root]
	assert(head, "OctopusRig: no root part " .. Data.Root)

	-- ⚠️ ПОЗУ ЗАПОМИНАЕМ ДО ПЕРВОГО СУСТАВА.
	-- По ней ниже считаются C1, а созданный сустав уже может подвинуть деталь —
	-- если модель к этому моменту в Workspace, замеры для следующих звеньев
	-- поедут одно за другим. Снимок делает порядок сборки неважным.
	local rest = {}
	for name, p in pairs(parts) do rest[name] = p.CFrame end

	if #missing > 0 then
		table.sort(missing)
		warn("OctopusRig: собран без деталей — " .. table.concat(missing, ", ")
			.. " (импортёр их не привёз; на остальное не влияет)")
	end

	for _, d in ipairs(model:GetDescendants()) do
		if d:IsA("Motor6D") or d:IsA("Weld") or d:IsA("WeldConstraint") then
			d:Destroy()
		end
	end

	local root = model:FindFirstChild("HumanoidRootPart")
	if not root then
		root = Instance.new("Part")
		root.Name = "HumanoidRootPart"
		root.Size = Vector3.new(1, 1, 1)
		root.Transparency = 1
		root.CanCollide = false
		root.CanQuery = false
		-- ⚠️ КОРЕНЬ СТАВИМ РОВНО ПО МИРУ, А НЕ ПО ПОВОРОТУ ГОЛОВЫ.
		-- Всё, что кладётся на RootJoint, считается в осях ЭТОГО парта: и
		-- вертикальный ход Emerge/Submerge, и качка на волне. Возьми мы поворот
		-- головы (а импортёр разворачивает детали как ему удобно) — «вверх»
		-- поехало бы вбок. Ровно та же ловушка, что со StudsOffsetWorldSpace у
		-- стрелки над бревном. Поворот головы при этом не теряется: он уходит
		-- в C1 ниже.
		root.CFrame = CFrame.new(rest[Data.Root].Position)
		root.Parent = model
	end
	-- it hangs in the water: the drift is animated, not physical
	root.Anchored = true

	local motors = {}
	local rj = Instance.new("Motor6D")
	rj.Name = "RootJoint"
	rj.Part0, rj.Part1 = root, head
	-- C0 единичный, значит оси сустава — мировые; собственный поворот головы
	-- прячем в C1, иначе она встала бы по корню и модель развернуло
	rj.C1 = rest[Data.Root]:ToObjectSpace(root.CFrame)
	rj.Parent = root
	motors.Root = rj

	-- ⚠️ ТОЧКУ ВРАЩЕНИЯ БЕРЁМ ИЗ ДАННЫХ, А ПОЗУ ПОКОЯ — С САМОЙ МОДЕЛИ.
	-- Motor6D не «запоминает, где деталь стояла»: он ДВИГАЕТ Part1, пока не
	-- сойдётся Part0.CFrame * C0 == Part1.CFrame * C1. Пара чистых сдвигов, как
	-- было записано в таблице, требует вдобавок, чтобы обе детали смотрели
	-- одинаково, — а импортёр привозит каждую со своим поворотом. Оттого детали
	-- и слетелись в кучу под чужими углами.
	-- Поэтому из таблицы берём только C0 (где сустав на РОДИТЕЛЕ — вокруг этой
	-- точки деталь и будет крутиться), а C1 замеряем по текущей позе: клон ещё
	-- не тронут, детали стоят ровно так, как в модели. Поза покоя после этого
	-- совпадает с моделью всегда, что бы ни было в данных.
	local scale = importScale(parts)
	if math.abs(scale - 1) > 0.05 then
		print(("OctopusRig: масштаб импорта ×%.3f — смещения суставов пересчитаны")
			:format(scale))
	end

	local maxDrift = 0
	for _, j in ipairs(Data.Joints) do
		local child = parts[j.part1]
		if child then
			local parent = parts[j.part0]
			local childRest = rest[j.part1]
			local parentRest = parent and rest[j.part0] or rest[Data.Root]
			local m = Instance.new("Motor6D")
			m.Name = j.name
			if parent then
				m.Part0, m.Part1 = parent, child
				m.C0 = CFrame.new(j.c0 * scale)
				-- насколько замеры экспортёра расходятся с тем, как модель
				-- реально собрана: расходятся сильно — точка вращения не там
				local a = (parentRest * CFrame.new(j.c0 * scale)).Position
				local b = (childRest * CFrame.new(j.c1 * scale)).Position
				maxDrift = math.max(maxDrift, (a - b).Magnitude)
			else
				-- ⚠️ ЗВЕНО ОСТАЛОСЬ БЕЗ РОДИТЕЛЯ — ВЕШАЕМ НА ГОЛОВУ ПО МЕСТУ.
				-- Пропала середина щупальца: кончик не к чему крепить, а он
				-- незаанкорен и просто утонет отдельно от туши.
				m.Part0, m.Part1 = head, child
				m.C0 = CFrame.new(parentRest:ToObjectSpace(childRest).Position)
			end
			m.C1 = childRest:ToObjectSpace(parentRest * m.C0)
			m.Parent = m.Part0
			motors[j.name] = m
		end
	end
	if maxDrift > 0.5 then
		warn(("OctopusRig: замеры суставов расходятся с моделью до %.2f стада — "
			.. "поза покоя правильная, но точки вращения смещены; перегенерируй "
			.. "OctopusRigData под этот импорт"):format(maxDrift))
	end
	model.PrimaryPart = root

	local self = setmetatable({
		model = model, root = root, head = head, parts = parts, motors = motors,
		hits = 0, alive = true, clickable = false, lastHit = 0,
		animator = Animator.new(motors),
	}, Rig)
	self.animator:setBase("SwimIdle", 0)
	return self
end

--[[ Spawns it already underwater and lets it rise. Pass rise = false to have it
     appear straight in the working pose, which is what you want for testing. ]]
function Rig.spawn(cframe: CFrame, parent: Instance?, rise: boolean?)
	local template = script.Parent:FindFirstChild("Model")
	assert(template, "OctopusRig: no Model next to the module")
	local model = template:Clone()
	local octo = Rig.setup(model)
	model.Parent = parent or workspace
	model:PivotTo(cframe)
	octo:bind()
	if rise ~= false then
		octo:emerge()
	else
		octo.clickable = true
		octo:startTimer()
	end
	return octo
end

function Rig:bind()
	if self.conn then return end
	self.conn = RunService.Heartbeat:Connect(function(dt)
		self.animator:step(dt)
	end)
end

function Rig:unbind()
	if self.conn then
		self.conn:Disconnect()
		self.conn = nil
	end
end

--[[ Comes up out of the dark, settles into the idle, starts its clock. It is
     not clickable while still rising — a hit landing mid-emerge reads to the
     player as having hit nothing. ]]
function Rig:emerge(onDone)
	self.clickable = false
	self.animator:setBase("Emerge", 0)
	self.animator.onBaseDone = function(name)
		if name ~= "Emerge" or not self.alive then return end
		self.animator.onBaseDone = nil
		self.animator:setBase("SwimIdle", 0.3)
		self.clickable = true
		self:startTimer()
		if onDone then onDone(self) end
	end
end

--[[ Gives up and sinks. Cannot be hit any more; the model cleans itself up. ]]
function Rig:submerge(onDone)
	if not self.alive then return end
	self.clickable = false
	self:stopTimer()
	self.animator:setBase("Submerge", 0.25)
	self.animator.onBaseDone = function(name)
		if name ~= "Submerge" then return end
		self.animator.onBaseDone = nil
		self.alive = false
		if self.onEscaped then self.onEscaped(self) end
		if onDone then onDone(self) end
		self:destroy()
	end
end

function Rig:startTimer()
	self:stopTimer()
	if Rig.Lifetime and Rig.Lifetime > 0 then
		self.timer = task.delay(Rig.Lifetime, function()
			if self.alive and self.clickable then
				self:submerge()
			end
		end)
	end
end

function Rig:stopTimer()
	if self.timer then
		task.cancel(self.timer)
		self.timer = nil
	end
end

--[[ One click. Returns hits left, or 0 once it has broken. ]]
function Rig:hit()
	if not self.alive or not self.clickable then return Rig.MaxHits - self.hits end
	local now = os.clock()
	if now - self.lastHit < Rig.HitCooldown then
		return Rig.MaxHits - self.hits
	end
	self.lastHit = now
	self.hits += 1
	self.animator:fire("Hit", 1 + math.random() * 0.25)
	if self.hits >= Rig.MaxHits then
		self:breakApart()
		return 0
	end
	return Rig.MaxHits - self.hits
end

--[[ A ClickDetector on every part, so the whole silhouette is clickable rather
     than whichever piece the player happened to aim at. ]]
function Rig:onClick(callback)
	for _, p in pairs(self.parts) do
		local cd = Instance.new("ClickDetector")
		cd.MaxActivationDistance = 120
		cd.Parent = p
		cd.MouseClick:Connect(function()
			local left = self:hit()
			if callback then callback(left, self) end
		end)
	end
end

--[[ Death: shudder, then let go of every joint at once so the pieces scatter.
     Because the rig is already 21 loose parts, it is its own debris — no
     second model needed. Crown, collar and pendant are gold, so the wreck
     reads as spilled treasure with no extra props. ]]
function Rig:breakApart()
	if not self.alive then return end
	self.alive = false
	self.clickable = false
	self:stopTimer()
	self.animator.onBaseDone = nil
	self.animator:setBase("BreakUp", 0.08)

	task.delay(Animator.Clips.BreakUp.length, function()
		self:unbind()
		self.animator:stop()
		for _, m in pairs(self.motors) do
			m:Destroy()
		end
		local centre = self.head.Position
		for name, p in pairs(self.parts) do
			p.Anchored = false
			p.Massless = false
			p.CanCollide = true
			p.CanQuery = false
			local out = p.Position - centre
			if out.Magnitude < 0.1 then
				out = Vector3.new(math.random() - 0.5, 1, math.random() - 0.5)
			end
			out = out.Unit
			-- gold flies further and spins harder, so the eye follows it
			local gold = Rig.GoldNames[name] ~= nil
			p.AssemblyLinearVelocity = out * (gold and 34 or 22)
				+ Vector3.new(0, gold and 26 or 16, 0)
				+ Vector3.new(math.random() - 0.5, 0, math.random() - 0.5) * 8
			p.AssemblyAngularVelocity = Vector3.new(
				math.random() - 0.5, math.random() - 0.5, math.random() - 0.5)
				* (gold and 22 or 12)
			if not gold then
				DebrisSvc:AddItem(p, 6)
			end
		end
		if self.root then
			self.root:Destroy()
		end
		if self.onShatter then
			self.onShatter(self)
		end
	end)
end

function Rig:destroy()
	self:unbind()
	self:stopTimer()
	if self.model then
		self.model:Destroy()
	end
end

return Rig
